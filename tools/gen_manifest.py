#!/usr/bin/env python3
"""src/host/setup_manifest.c: the game files the Windows build's set-up
(src/host/setup_files.c) looks for in the user's copy, with their sizes and
SHA-256s, from an installed Civilization II Multiplayer Gold Edition (the
CD's installer, or the CD's DATA1.CAB unpacked into the installed layout,
with tools/extract_disc.py's KINGS, VIDEO and Music).

    gen_manifest.py [GAMEDIR]          (default: $CIV2_GAME, ~/Civ2)

Required: what the game reads -- civ2.exe (its resources), the resource
DLLs, the text, picture, map, scenario and sound files of the installation.
Optional: the CD's videos (VIDEO, KINGS), the Fantastic Worlds and Conflicts
scenarios (SCENARIO); checked the same way, copied when found.  The music
(Music/TrackNN.wav, the CD's audio tracks) varies with the rip: it has no
SHA-256, only a WAV header check.  Not copied: the documentation, and the
executables the reconstruction does not run (the map editor, the network
daemon and its timer DLL).  CIV2_TRACE_FILES traces (src/host/wasi.c) can
be given with --trace to check that everything the game opened is listed.
"""
import argparse
import hashlib
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import paths  # noqa: E402

OUT = os.path.join(paths.ROOT, 'src', 'host', 'setup_manifest.c')

# The installation's files the game does not read.
SKIP = {'readme.txt', 'civ2faq.txt', 'civ2fanw.txt', 'patch.txt', 'misc.txt', 'mapmenu.txt',
        'civ2map.exe', 'xdaemon.dll', 'timerdll.dll'}
# What the game writes (settings, saves, logs): never part of the manifest.
WRITTEN = ('civ.ini', 'civ2.dat', 'hallfame.dat', 'inter.dat', 'smeds.log', 'chatlog.txt')
REQUIRED_EXT = {'.exe', '.dll', '.txt', '.gif', '.mp', '.scn', '.sav', '.avi', '.wav'}


def classify(rel):
    """'required', 'optional' or None for a path relative to the game."""
    parts = rel.split('/')
    name = parts[-1].lower()
    top = parts[0].upper()
    if name in SKIP or name.startswith(WRITTEN) or name.endswith('.part'):
        return None
    if len(parts) == 1:
        if name.endswith('.sav') and name != 'tutorial.sav':
            return None             # the player's saved games
        return 'required' if os.path.splitext(name)[1] in REQUIRED_EXT else None
    if top == 'SOUND' and len(parts) == 2 and name.endswith('.wav'):
        return 'required'
    if top in ('VIDEO', 'KINGS') and len(parts) == 2 and name.endswith('.avi'):
        return 'optional'
    if top == 'SCENARIO':
        return 'optional'
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('game', nargs='?', default=paths.GAME)
    ap.add_argument('--trace', nargs='*', default=[], help='CIV2_TRACE_FILES logs to check against')
    a = ap.parse_args()
    rows = []
    for d, dirs, files in os.walk(a.game):
        dirs.sort()
        for f in sorted(files):
            full = os.path.join(d, f)
            rel = os.path.relpath(full, a.game).replace(os.sep, '/')
            kind = classify(rel)
            if kind:
                data = open(full, 'rb').read()
                rows.append((rel, len(data), hashlib.sha256(data).hexdigest(), kind))
    rows.sort(key=lambda r: (r[3] != 'required', r[0].lower()))
    if a.trace:
        listed = {r[0].lower() for r in rows}
        game = os.path.abspath(a.game).replace(os.sep, '/').lower().rstrip('/') + '/'
        missing = set()
        for t in a.trace:
            for line in open(t, errors='replace'):
                p = line.strip().lstrip('-').replace('\\', '/')
                if p.lower().startswith(game):
                    rel = p[len(game):]
                    if (rel.lower() not in listed and not rel.lower().startswith(('music/',) + WRITTEN)
                            and not rel.lower().endswith('.sav') and os.path.exists(os.path.join(a.game, rel))):
                        missing.add(rel)
        if missing:
            sys.exit('opened by the game but not in the manifest: %s' % ' '.join(sorted(missing)))
    out = ['/* Generated by tools/gen_manifest.py from an installed Civilization II',
           ' * Multiplayer Gold Edition (5.4.0f, the CD\'s release): the files set-up',
           ' * copies into GameData, where they go, their sizes and SHA-256s. */',
           '#include "setup.h"', '',
           'const SetupFile setup_manifest[] = {']
    for rel, size, sha, kind in rows:
        out.append('    {"%s", %d, "%s", %s},' % (rel, size, sha,
                                                 'SETUP_REQUIRED' if kind == 'required' else 'SETUP_OPTIONAL'))
    out += ['};', 'const int setup_manifest_count = (int)(sizeof setup_manifest / sizeof setup_manifest[0]);', '']
    open(OUT, 'w', newline='\n').write('\n'.join(out))
    req = sum(1 for r in rows if r[3] == 'required')
    print('wrote %s: %d required files (%.1f MB), %d optional (%.1f MB)' % (
        os.path.relpath(OUT, paths.ROOT), req, sum(r[1] for r in rows if r[3] == 'required') / 1e6,
        len(rows) - req, sum(r[1] for r in rows if r[3] != 'required') / 1e6))


if __name__ == '__main__':
    main()
