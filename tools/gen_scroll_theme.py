#!/usr/bin/env python3
"""Scroll bar parts as Wine's default theme draws them, cut from the output
of tools/probe/scrollprobe.c (run/scrollprobe.ppm), into
src/platform/scroll_theme.h.

Usage: sh tools/probe/run.sh scrollprobe (in the container), then
       python3 tools/gen_scroll_theme.py
"""
import os
import sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
im = Image.open(os.path.join(ROOT, 'run', 'scrollprobe.ppm')).convert('RGB')
assert all(r == g == b for r, g, b in im.getdata()), 'expected grey only'
im = im.convert('L')


def part(x, y, w=17, h=17):
    return [im.getpixel((x + i, y + j)) for j in range(h) for i in range(w)]


# (name, x, y) of each 17x17 part in the probe's layout
PARTS = [
    ('up', 10, 10), ('down', 10, 193), ('vthumb', 10, 27),
    ('up_off', 100, 10), ('down_off', 100, 193),
    ('left', 200, 10), ('right', 383, 10), ('hthumb', 217, 10),
    ('left_off', 200, 100), ('right_off', 383, 100),
]
parts = {n: part(x, y) for n, x, y in PARTS}

# The window scroll bars use the same parts (only the track differs).
checks = [('up', 333, 170), ('down', 333, 287), ('left', 200, 303), ('right', 317, 303),
          ('up', 483, 170), ('down', 483, 383)]
for n, x, y in checks:
    if part(x, y) != parts[n]:
        sys.exit('window scroll bar part %s at %d,%d differs' % (n, x, y))
# Tracks: controls 245/255 by parity (relative to the control), window bars 245.
assert im.getpixel((12, 50)) == 245 and im.getpixel((13, 50)) == 255
assert im.getpixel((340, 240)) == 245

out = ['/* Generated by tools/gen_scroll_theme.py from tools/probe/scrollprobe.c:',
       ' * 17x17 grey scroll bar parts of Wine\'s default theme. */', '']
for n, _, _ in PARTS:
    px = parts[n]
    out.append('static const unsigned char sb_%s[289] = {' % n)
    for j in range(17):
        out.append('    ' + ', '.join('0x%02x' % v for v in px[17 * j:17 * j + 17]) + ',')
    out.append('};')
out.append('')
open(os.path.join(ROOT, 'src', 'platform', 'scroll_theme.h'), 'w').write('\n'.join(out))
print('wrote %d parts' % len(PARTS))
